for (const template of catalog) {
  for (const item of template.roles) {
    Object.freeze(item.responsibilities)
    Object.freeze(item)
  }
  Object.freeze(template.roles)
  Object.freeze(template)
}
Object.freeze(catalog)

export function listBuiltinTemplates(): BuiltinTemplateSummary[] {
  return catalog.map(({ id, name, avatar, description, roles }) => ({
    id, name, avatar, description, roleCount: roles.length, roleNames: roles.map((item) => item.name),
  }))
}

export function getBuiltinTemplate(id: string): BuiltinTemplate | undefined {
  const template = catalog.find((item) => item.id === id)
  return template ? structuredClone(template) : undefined
}
