test('automatic scheduling uses exact schema decisions and null finishes without fabricating another speaker', async ({ desktop, provider }) => {
  const agents = await team(desktop, provider)
  const { page } = desktop
  await page.getByRole('button', { name: '模型设置', exact: true }).click()
  await page.getByRole('combobox', { name: '默认调度模型', exact: true }).selectOption({ label: 'local-e2e-model' })
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  const goal = '自动选择合适成员并完成任务 ' + 'required goal detail '.repeat(160) + '保留最终验收要求'
  await page.getByLabel('消息内容', { exact: true }).fill(goal)
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  const consent = page.getByRole('dialog', { name: '云端模型授权' })
  await expect(consent).toContainText('自动选人')
  await expect(consent).toContainText('完整当前 CEO 目标')
  await expect(consent).toContainText('每 10 个完成轮次的摘要')
  expect(provider.requests).toHaveLength(0)
  await consent.getByRole('checkbox').check(); await consent.getByRole('button', { name: '同意并发送', exact: true }).click()
  await expect.poll(() => provider.requests.length).toBe(1)
  expect(provider.requests[0].stream).toBe(false)
  expect(JSON.parse(provider.requests[0].messages[1].content!)).toMatchObject({ currentCeoGoal: goal, latestCompletedAgentMessage: '' })
  const [model] = await page.evaluate(() => window.agentTeam.models.list())
  const withinBudget = (index: number) => expect(Buffer.byteLength(JSON.stringify(provider.requests[index].messages), 'utf8') + 256 + provider.requests[index].max_tokens).toBeLessThanOrEqual(model.contextWindow ?? 8192)
  expect(provider.requests[0].max_tokens).toBe(model.maxOutputTokens ?? 1024)
  withinBudget(0)
  provider.json(JSON.stringify({ nextSpeaker: agents[1].id, reason: 'Beta 负责最终核对' }))
  await expect.poll(() => provider.requests.length).toBe(2)
  await expect(page.getByRole('region', { name: 'CEO 任务控制' })).toContainText('Beta 负责最终核对')
  expect(provider.requests[1].stream).toBe(true)
  provider.delta('自动选择 Beta 的交付。'); provider.complete()
  await expect.poll(() => provider.requests.length).toBe(3)
  expect(JSON.parse(provider.requests[2].messages[1].content!)).toMatchObject({ currentCeoGoal: goal, latestCompletedAgentMessage: '自动选择 Beta 的交付。' })
  withinBudget(2)
  provider.json(JSON.stringify({ nextSpeaker: null, reason: '任务已完成，无需继续发言' }))
  await expect(page.getByText('已完成', { exact: true })).toBeVisible()
  await page.reload()
  const state = await snapshot(page)
  expect(state.turns.map((turn) => turn.agentId)).toEqual([agents[1].id])
  expect(state.events.filter((event) => event.eventType === 'speaker_decided').map((event) => event.displayReason)).toEqual(['Beta 负责最终核对', '任务已完成，无需继续发言'])
  expect(provider.requests).toHaveLength(3)
})

