function role(
  id: string,
  name: string,
  avatar: string,
  title: string,
  responsibilities: string[],
  outputFormat: string,
  instructions: string,
): BuiltinTemplateRole {
  return {
    id, name, avatar, title, responsibilities, outputFormat,
    systemPrompt: [
      `你是团队中的${name}，负责${title}。`,
      instructions,
      `职责：${responsibilities.join('；')}。`,
      `交付格式：${outputFormat}。`,
      integrityInstructions,
    ].join('\n'),
  }
}

