test('pending approval blocks Beta; executing one overwrite still requires explicit continuation', async ({ desktop, provider }) => {
  await writeWorkspaceFile(desktop, 'existing.md', '原始内容')
  const agents = await team(desktop, provider, ['write_file'])
  await mentions(desktop.page, ['Alpha', 'Beta']); await submitFirst(desktop.page)
  await expect.poll(() => provider.requests.length).toBe(1)
  provider.toolCall('write_file', { path: 'existing.md', content: '审批后写入' }, 'v03-overwrite')
  const controls = desktop.page.getByRole('region', { name: 'CEO 任务控制' })
  await expect(controls).toContainText('等待 CEO 审批')
  await expect(controls.getByRole('button', { name: '继续当前任务', exact: true })).toBeDisabled()
  await desktop.page.reload()
  await desktop.page.getByRole('tab', { name: '工具与审批', exact: true }).click()
  const approvals = desktop.page.getByRole('region', { name: '安全审批', exact: true })
  await approvals.getByRole('button', { name: '批准', exact: true }).click()
  await expect(approvals).toContainText('approved')
  await expect(desktop.page.getByRole('button', { name: '继续当前任务', exact: true })).toBeDisabled()
  expect(await readFile(join(desktop.workspace, 'existing.md'), 'utf8')).toBe('原始内容')
  expect(provider.requests).toHaveLength(1)
  await approvals.getByRole('button', { name: '执行已批准操作', exact: true }).click()
  await expect.poll(async () => readFile(join(desktop.workspace, 'existing.md'), 'utf8')).toBe('审批后写入')
  await expect(desktop.page.getByRole('button', { name: '继续当前任务', exact: true })).toBeEnabled()
  expect(provider.requests).toHaveLength(1)
  let state = await snapshot(desktop.page)
  const [approval] = await desktop.page.evaluate((id) => window.agentTeam.approvals.list(id), state.runs[0].id)
  expect(await desktop.page.evaluate(async (id) => { try { await window.agentTeam.approvals.runApproved(id); return false } catch { return true } }, approval.id)).toBe(true)
  await desktop.page.getByRole('button', { name: '继续当前任务', exact: true }).click()
  await expect.poll(() => provider.requests.length).toBe(2)
  expect(JSON.stringify(provider.requests[1].messages)).toContain('你是 Alpha')
  provider.delta('Alpha 已核验审批效果，不重复写入。'); provider.complete()
  await expect.poll(() => provider.requests.length).toBe(3)
  provider.delta('Beta 继续核对。'); provider.complete()
  await paused(desktop.page)
  state = await snapshot(desktop.page)
  expect(state.turns.map((turn) => [turn.agentId, turn.status])).toEqual([[agents[0].id, 'cancelled'], [agents[0].id, 'completed'], [agents[1].id, 'completed']])
  const tools = await desktop.page.evaluate((id) => window.agentTeam.tools.list(id), state.runs[0].id)
  expect(tools).toHaveLength(1); expect(tools[0].status).toBe('completed')
  expect(await readFile(join(desktop.workspace, 'existing.md'), 'utf8')).toBe('审批后写入')
})

test('CEO interruption disconnects old stream and rejects a late previous Run fragment', async ({ desktop, provider }) => {
  const agents = await team(desktop, provider)
  await mentions(desktop.page, ['Alpha']); await submitFirst(desktop.page)
  await expect.poll(() => provider.requests.length).toBe(1)
  provider.delta('旧任务临时输出')
  await expect(desktop.page.getByRole('log')).toContainText('旧任务临时输出')
  const previous = await snapshot(desktop.page)
  await mentions(desktop.page, ['Beta'], '改为核对新目标 ')
  await desktop.page.getByRole('button', { name: '中断并发送新指令', exact: true }).click()
  await expect.poll(() => provider.disconnectedRequests).toContain(0)
  await expect.poll(() => provider.requests.length).toBe(2)
  // Simulate an already queued Main-to-Preload fragment from the cancelled scope.
  await desktop.app.evaluate(({ BrowserWindow }, stale) => {
    BrowserWindow.getAllWindows()[0].webContents.send('message:stream', stale)
  }, { taskRunId: previous.runs[0].id, generation: previous.runs[0].generation, turnId: previous.turns[0].id, agentId: agents[0].id, step: 1, type: 'delta', content: 'LATE_OLD_RUN_FRAGMENT' })
  provider.delta('Beta 新任务完成。'); provider.complete()
  await paused(desktop.page)
  await expect(desktop.page.getByRole('log')).not.toContainText('LATE_OLD_RUN_FRAGMENT')
  await expect(desktop.page.getByRole('log')).not.toContainText('旧任务临时输出')
  const state = await snapshot(desktop.page)
  expect(state.runs.map((run) => run.status)).toEqual(['cancelled', 'paused'])
  expect(state.messages.map((message) => message.authorName)).toEqual(['CEO', 'CEO', 'Beta'])
})

test('CEO interruption uses the newly selected conversation model and requires its own consent', async ({ desktop, provider }) => {
  await createProject(desktop)
  const { page } = desktop
  await configureModel(page, provider.url)
  await sendWithConsent(page, '旧模型的任务')
  await expect.poll(() => provider.requests.length).toBe(1)
  expect(provider.requests[0].model).toBe('local-e2e-model')
  const old = await snapshot(page)
  await page.getByRole('button', { name: '模型设置', exact: true }).click()
  const settings = page.getByRole('dialog', { name: '模型设置', exact: true })
  await settings.getByRole('combobox', { name: '模型服务商', exact: true }).selectOption('openai')
  await settings.getByLabel('服务地址', { exact: true }).fill(provider.url)
  await settings.getByLabel('模型名称', { exact: true }).fill('replacement-e2e-model')
  await settings.getByLabel('API Key', { exact: true }).fill('e2e-second-local-only-key')
  await settings.getByRole('button', { name: '保存配置', exact: true }).click()
  await expect(settings.getByRole('status')).toHaveText('模型配置已保存')
  await settings.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.getByLabel('对话模型').locator('option:checked')).toHaveText('replacement-e2e-model')
  const selected = (await page.evaluate(() => window.agentTeam.models.list())).find((model) => model.modelName === 'replacement-e2e-model')!
  await page.getByLabel('消息内容', { exact: true }).fill('新模型处理的新目标')
  await page.getByRole('button', { name: '中断并发送新指令', exact: true }).click()
  const consent = page.getByRole('dialog', { name: '云端模型授权' })
  await expect(consent).toContainText('replacement-e2e-model')
  expect(provider.requests).toHaveLength(1)
  expect((await snapshot(page)).runs[0].status).toBe('running')
  await consent.getByRole('checkbox').check(); await consent.getByRole('button', { name: '同意并发送', exact: true }).click()
  await expect.poll(() => provider.disconnectedRequests).toContain(0)
  await expect.poll(() => provider.requests.length).toBe(2)
  expect(provider.requests[1]).toMatchObject({ model: 'replacement-e2e-model', stream: true })
  expect(provider.requests[1].messages.at(-1)?.content).toBe('新模型处理的新目标')
  provider.delta('新模型任务已完成。'); provider.complete()
  await expect(page.getByText('已完成', { exact: true })).toBeVisible()
  const state = await snapshot(page)
  expect(state.runs.map((run) => [run.modelConfigId, run.status])).toEqual([[old.runs[0].modelConfigId, 'cancelled'], [selected.id, 'completed']])
})

test('restart during an Agent stream pauses without replay and resumes only after an explicit click', async ({ desktop, provider }) => {
  await team(desktop, provider)
  await mentions(desktop.page, ['Alpha']); await submitFirst(desktop.page)
  await expect.poll(() => provider.requests.length).toBe(1)
  provider.delta('重启前未完成分片')
  await expect(desktop.page.getByRole('log')).toContainText('重启前未完成分片')
  await desktop.restart()
  await paused(desktop.page)
  expect(provider.requests).toHaveLength(1)
  await expect(desktop.page.getByRole('log')).not.toContainText('重启前未完成分片')
  await desktop.page.getByRole('button', { name: '继续当前任务', exact: true }).click()
  await expect.poll(() => provider.requests.length).toBe(2)
  provider.delta('恢复后新一轮完整输出。'); provider.complete()
  await paused(desktop.page)
  const state = await snapshot(desktop.page)
  expect(state.turns.map((turn) => turn.status)).toEqual(['cancelled', 'completed'])
  expect(state.messages.map((message) => message.content)).not.toContain('重启前未完成分片')
  expect(state.runs[0].generation).toBeGreaterThan(state.turns[0].generation)
})
